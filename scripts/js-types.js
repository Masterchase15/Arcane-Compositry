/**
 * scripts/js-types.js - writes a small .d.ts beside each plain-JavaScript file
 * the React code imports, listing its exports as untyped (`any`), so TypeScript
 * does not guess their types. Run it after adding an export to one of them:
 *
 *   npm run js-types
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = [
  'shared/rules/constants.js', 'shared/rules/formulas.js', 'shared/rules/character.js', 'shared/rules/codex-content.js',
  'web/src/lib/calculators.js', 'web/src/content/guide.js',
];

for (const rel of FILES) {
  const src = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const names = [...src.matchAll(/^export\s+(?:const|let|function|async function|class)\s+(\w+)/gm)].map((m) => m[1]);
  for (const m of src.matchAll(/^export\s*\{([^}]+)\}/gm)) names.push(...m[1].split(',').map((s) => s.trim().split(/\s+as\s+/).pop()));
  const out = `// Generated by scripts/js-types.js - the exports of ${path.basename(rel)}, untyped. Do not edit.\n`
    + [...new Set(names)].map((n) => `export declare const ${n}: any;`).join('\n') + '\n';
  fs.writeFileSync(path.join(ROOT, rel.replace(/\.js$/, '.d.ts')), out);
  console.log(`${rel}: ${names.length} exports`);
}
